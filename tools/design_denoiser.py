"""Generate f32 FFT twiddles and periodic sqrt-Hann; Python stdlib only."""
import math
from pathlib import Path
import struct


def literal(value):
    value = struct.unpack('<f', struct.pack('<f', value))[0]
    text = format(value, '.9g')
    return text if '.' in text or 'e' in text else text + '.0'


size = 256
lines = ['//! Generated by tools/design_denoiser.py; actual f32 coefficients.',
         '#![allow(clippy::excessive_precision)]',
         'pub const WINDOW: [f32; 256] = [']
lines += ['    ' + literal(math.sqrt(max(0, 0.5 - 0.5 * math.cos(2 * math.pi * n / size)))) + ','
          for n in range(size)]
lines += ['];', 'pub const TWIDDLE: [(f32, f32); 128] = [']
lines += [f'    ({literal(math.cos(2 * math.pi * n / size))}, {literal(-math.sin(2 * math.pi * n / size))}),' for n in range(size // 2)]
lines += ['];', '']
(Path(__file__).resolve().parent.parent / 'src/denoiser_tables.rs').write_text('\n'.join(lines), encoding='utf-8')
