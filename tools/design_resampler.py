"""Generate fractional-delay filters for the fixed-packet USB clock bridge."""
import math
import json
import struct
from pathlib import Path
from design_filter import i0

root = Path(__file__).resolve().parents[1]
lines = ['// Generated by tools/design_resampler.py; oldest sample first.',
         '// 48 taps, 33 phases, Kaiser beta=6, cutoff=6880/16000.',
         'pub const PHASES: [[f32; 48]; 33] = [']
phases = []
for phase in range(33):
    taps = []
    for j in range(48):
        distance = 47-j + phase/32 - 23
        sinc = 0.86 if distance == 0 else math.sin(math.pi*0.86*distance)/(math.pi*distance)
        window = i0(6*math.sqrt(max(0, 1-(distance/24)**2)))/i0(6) if abs(distance) <= 24 else 0
        taps.append(sinc*window)
    scale = sum(taps)
    literals = []
    rounded_taps = []
    for x in taps:
        expected = struct.pack('<f', x/scale)
        rounded = struct.unpack('<f', expected)[0]
        rounded_taps.append(rounded)
        for digits in range(1, 10):
            literal = format(rounded, f'.{digits}g')
            if struct.pack('<f', float(literal)) == expected:
                if '.' not in literal and 'e' not in literal: literal += '.0'
                literals.append(literal+'_f32')
                break
    assert len(literals) == 48
    phases.append(rounded_taps)
    lines.append('    ['+', '.join(literals)+'],')
lines += ['];', '']
(root/'src/resampler_coeffs.rs').write_text('\n'.join(lines), encoding='utf-8')
response_db = []
for index in range(65):
    phase = min(index//2, 31)
    blend = index/2-phase
    taps = [a+(b-a)*blend for a,b in zip(phases[phase], phases[phase+1])]
    for frequency in range(0, 6001, 20):
        angle = 2*math.pi*frequency/16000
        re = sum(x*math.cos(angle*i) for i,x in enumerate(taps))
        im = sum(x*math.sin(angle*i) for i,x in enumerate(taps))
        response_db.append(20*math.log10(math.hypot(re,im)))
report = {'taps':48, 'phase_intervals':32, 'coefficient_phases':33,
          'rate_hz':16000, 'cutoff_hz':6880, 'beta':6,
          'fractional_delay_samples':23,
          'passband_grid_hz':[0,6000,20], 'tested_fractional_phases':65,
          'passband_db_min':min(response_db), 'passband_db_max':max(response_db),
          'scope':'ASRC filter only; excludes CIC, PDM decimation FIR, DC blocker, microphone and Windows processing.'}
(root/'artifacts/stage4-resampler-design.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print(json.dumps(report,indent=2))
