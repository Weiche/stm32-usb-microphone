"""Generate the checked-in 64 kHz -> 16 kHz low-pass FIR (Python stdlib)."""
import json
import math
import struct
from pathlib import Path

TAPS = 191
RATE = 64000
CUTOFF = 7000
BETA = 7.8562


def i0(value):
    total = term = 1.0
    for k in range(1, 100):
        term *= (value / (2*k)) ** 2
        total += term
        if term < total * 1e-16: break
    return total


def coefficients():
    result = []
    center = (TAPS-1)/2
    for n in range(TAPS):
        m = n-center
        sinc = 2*CUTOFF/RATE if m == 0 else math.sin(2*math.pi*CUTOFF/RATE*m)/(math.pi*m)
        window = i0(BETA*math.sqrt(max(0, 1-(m/center)**2)))/i0(BETA)
        result.append(sinc*window)
    scale = sum(result)
    return [x/scale for x in result]


def response(taps, frequency):
    phase = 2*math.pi*frequency/RATE
    real = sum(x*math.cos(phase*i) for i,x in enumerate(taps))
    imag = sum(x*math.sin(phase*i) for i,x in enumerate(taps))
    return math.hypot(real,imag)


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    taps = [struct.unpack('<f', struct.pack('<f', x))[0] for x in coefficients()]
    # Find the shortest decimal that reproduces each intended f32 coefficient.
    def literal(tap):
        expected=struct.pack('<f',tap)
        for digits in range(1,10):
            value=format(tap,f'.{digits}g')
            if struct.pack('<f',float(value))==expected:
                if '.' not in value and 'e' not in value: value += '.0'
                return value+'_f32'
        raise ValueError('No f32 round-trip literal')
    lines = ["// Generated by tools/design_filter.py: fs=64000, fc=7000, Kaiser beta=7.8562.",
             "// 191 taps; unity DC gain. Regenerate and review frequency response together.",
             "pub const FIR: [f32; 191] = ["]
    lines += [f"    {literal(tap)}," for tap in taps]
    lines += ["];", ""]
    (root/'src/fir_coeffs.rs').write_text('\n'.join(lines), encoding='utf-8')
    pass_db = [20*math.log10(response(taps, f)) for f in range(0,6001,20)]
    stop_db = [20*math.log10(max(response(taps,f),1e-15)) for f in range(8000,32001,20)]
    report = {'taps':TAPS, 'input_rate_hz':RATE, 'output_rate_hz':16000,
              'cutoff_hz':CUTOFF, 'passband_0_6000_db_min':min(pass_db),
              'passband_0_6000_db_max':max(pass_db), 'stopband_8000_32000_db_max':max(stop_db),
              'fir_group_delay_seconds':(TAPS-1)/2/RATE,
              'note':'FIR-only response. CIC droop, DC blocker and quantization are tested separately.'}
    (root/'artifacts/stage3-filter-design.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))
